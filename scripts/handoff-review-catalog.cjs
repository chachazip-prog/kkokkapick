const fs=require('node:fs'),assert=require('node:assert/strict');
assert.equal(process.env.GITHUB_REPOSITORY,'chachazip-prog/kkokkapick','Only this repository may receive review data');
assert.equal(process.env.GITHUB_REF,'refs/heads/codex/release-ui-rebuild','Only the review branch may receive this data');
assert.equal(process.env.GITHUB_EVENT_NAME,'workflow_dispatch','Manual handoff only');
const names=['adpick-biz-products.json','catalog.json','price-history.json'];
const documents=Object.fromEntries(names.map(name=>[name,JSON.parse(fs.readFileSync('.review-catalog/'+name,'utf8'))]));
const catalog=documents['catalog.json'],source=documents['adpick-biz-products.json'];
assert.ok(Array.isArray(catalog.products)&&catalog.products.length>=250,'Incomplete catalog');
assert.equal(catalog.productCount,catalog.products.length);
assert.ok(Array.isArray(source.products),'Invalid source offers');
assert.equal(source.count,source.products.length);
assert.equal(catalog.sourceCount,source.count);
assert.ok(Number.isFinite(Date.parse(catalog.expiresAt))&&Date.parse(catalog.expiresAt)>Date.now(),'Expired review catalog');
assert.ok(Number.isFinite(Date.parse(source.expiresAt))&&Date.parse(source.expiresAt)>Date.now(),'Expired source offers');
const observed=Date.parse(catalog.syncedAt),expiry=Date.parse(catalog.expiresAt);
assert.ok(Number.isFinite(observed)&&observed<=Date.now()+300000,'Invalid observation time');
assert.equal(observed,Date.parse(source.syncedAt),'Source/catalog observation mismatch');
assert.equal(expiry,Date.parse(source.expiresAt),'Source/catalog expiry mismatch');
assert.ok(expiry>observed&&expiry-observed<=24*3600000,'TTL must not exceed 24 hours');
assert.equal(catalog.storagePolicy,'ttl_cache');assert.equal(source.storagePolicy,'ttl_cache');
assert.ok(source.imageHealth?.rate>=0.8,'Insufficient verified original image health');
assert.ok(Array.isArray(documents['price-history.json'].events),'Invalid price history');
const previous=JSON.parse(fs.readFileSync('data/catalog.json','utf8'));
assert.ok(Date.parse(catalog.syncedAt)>=Date.parse(previous.syncedAt),'Never replace a newer source snapshot');
assert.ok(catalog.products.length>=previous.products.length*0.65,'Unexpected coverage collapse');
for(const name of names)fs.writeFileSync('data/'+name,JSON.stringify(documents[name],null,2)+'\n');
console.log(JSON.stringify({products:catalog.productCount,offers:catalog.sourceCount,images:source.imageHealth,productFacts:source.productFacts,syncedAt:catalog.syncedAt,expiresAt:catalog.expiresAt}));
